#!/bin/bash
# Build the JARVIS Music Shorts Factory desktop apps as SINGLE-FILE executables:
#   JARVIS-ShortsFactory.exe      (Windows x64)
#   JARVIS-ShortsFactory          (Linux x64)
#   JARVIS-ShortsFactory          (macOS x64)
# Everything (UI + server + dependencies) is baked into one executable via
# Node SEA (single executable application). Nothing to install — double-click.
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TOOLS="$ROOT/tools/ext"
APP="$ROOT/apps/desktop"
BT="$ROOT/apps/desktop-build"
DIST="$ROOT/dist"
BUILD="$APP/build"
VER="1.0.0"

NODE_LINUX="$TOOLS/node-linux/nodejs_wheel/bin/node"
SEA_CONFIG="$BUILD/sea-config.json"
BLOB="$BUILD/sea.blob"

mkdir -p "$BUILD" "$APP/gen" "$DIST"

echo "== 1/6 install build tools + app deps =="
( cd "$BT" && npm install --no-audit --no-fund >/dev/null )
( cd "$APP" && npm ci --no-audit --no-fund >/dev/null )

echo "== 2/6 embed UI + socket.io client into gen/embedded.js =="
python3 - "$APP" <<'EOF'
import json, sys, pathlib
app = pathlib.Path(sys.argv[1])
ui = app / 'ui' / 'index.html'
sio = app / 'node_modules' / 'socket.io' / 'client-dist' / 'socket.io.js'
out = app / 'gen' / 'embedded.js'
out.parent.mkdir(exist_ok=True)
src = "// generated by scripts/build-desktop.sh -- do not edit\n"
src += "module.exports.UI_FILES = " + json.dumps({'index.html': ui.read_text()}) + ";\n"
src += "module.exports.SOCKET_IO_CLIENT = " + json.dumps(sio.read_text()) + ";\n"
out.write_text(src)
print('embedded', ui.stat().st_size, '+', sio.stat().st_size, 'bytes')
EOF

echo "== 3/6 bundle server into one JS (esbuild) =="
"$BT/node_modules/.bin/esbuild" "$APP/index.js" \
  --bundle --platform=node --format=cjs \
  --external:bufferutil --external:utf-8-validate \
  --outfile="$BUILD/sea-main.cjs" --log-level=warning

echo "== 4/6 create SEA blob =="
cat > "$SEA_CONFIG" <<EOF
{
  "main": "$BUILD/sea-main.cjs",
  "output": "$BLOB",
  "disableExperimentalSEAWarning": true,
  "useSnapshot": false,
  "useCodeCache": false
}
EOF
"$NODE_LINUX" --experimental-sea-config "$SEA_CONFIG"
ls -la "$BLOB"

echo "== 5/6 inject blob into platform node binaries =="
FUSE="NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2"

make_exe () {
  local srcbin="$1" outname="$2"
  cp "$srcbin" "$BUILD/$outname"
  ( cd "$BT" && npx --no-install postject "$BUILD/$outname" NODE_SEA_BLOB "$BLOB" \
      --sentinel-fuse "$FUSE" >/dev/null )
  echo "  built $outname"
}

make_exe "$TOOLS/node-win/nodejs_wheel/node.exe"        "JARVIS-ShortsFactory.exe"
make_exe "$TOOLS/node-linux/nodejs_wheel/bin/node"      "JARVIS-ShortsFactory-linux"
make_exe "$TOOLS/node-mac/nodejs_wheel/bin/node"        "JARVIS-ShortsFactory-mac"

echo "== 6/6 assemble bundles =="
for plat in win64 linux64 mac-x64; do
  out="$DIST/JARVIS-MusicShortsFactory-$plat"
  rm -rf "$out"; mkdir -p "$out"
  cp "$APP/.env.example" "$APP/README-DESKTOP.txt" "$out/"
done
cp "$BUILD/JARVIS-ShortsFactory.exe"   "$DIST/JARVIS-MusicShortsFactory-win64/"
cp "$BUILD/JARVIS-ShortsFactory-linux" "$DIST/JARVIS-MusicShortsFactory-linux64/JARVIS-ShortsFactory"
cp "$BUILD/JARVIS-ShortsFactory-mac"   "$DIST/JARVIS-MusicShortsFactory-mac-x64/JARVIS-ShortsFactory"
chmod +x "$DIST/JARVIS-MusicShortsFactory-linux64/JARVIS-ShortsFactory" \
         "$DIST/JARVIS-MusicShortsFactory-mac-x64/JARVIS-ShortsFactory"
# bare exe at dist root for direct download
cp "$BUILD/JARVIS-ShortsFactory.exe" "$DIST/JARVIS-ShortsFactory-win64.exe"

cd "$DIST"
for d in JARVIS-MusicShortsFactory-win64 JARVIS-MusicShortsFactory-linux64 JARVIS-MusicShortsFactory-mac-x64; do
  rm -f "$d.zip"
  python3 -c "import shutil; shutil.make_archive('$d', 'zip', '.', '$d')"
  ls -la "$d.zip"
done
ls -la JARVIS-ShortsFactory-win64.exe
echo "== desktop builds done =="
